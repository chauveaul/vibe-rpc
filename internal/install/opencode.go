// OpenCode has no shell-hook config like Claude Code; it loads JS plugins from
// ~/.config/opencode/plugin/. vibe-rpc installs a tiny plugin that forwards
// OpenCode's events to `vibe-rpc hook <event> --source opencode` in the same
// JSON shape the Claude Code hooks use, so presence, analytics and the notch's
// permission alerts all work unchanged.
//
// OpenCode 1.x and 2.x have incompatible plugin APIs. 1.x calls each exported
// function and reads the hooks object it returns; 2.x only accepts a default
// export shaped { id, setup } and rejects anything else. So the plugin is
// rendered for the OpenCode that's installed, and re-running `vibe-rpc install`
// after a major OpenCode upgrade rewrites it.

const openCodePluginMarker = "vibe-rpc:opencode-plugin"

// OpenCodeConfigDir is OpenCode's global config dir ($OPENCODE_CONFIG_DIR,
// then $XDG_CONFIG_HOME/opencode, then ~/.config/opencode).
func OpenCodeConfigDir() string {
	if d := os.Getenv("OPENCODE_CONFIG_DIR"); d != "" {
		return d
	}
	if x := os.Getenv("XDG_CONFIG_HOME"); x != "" {
		return filepath.Join(x, "opencode")
	}
	return filepath.Join(paths.HomeDir(), ".config", "opencode")
}

// OpenCodePluginPath is where vibe-rpc's plugin lives.
func OpenCodePluginPath() string {
	return filepath.Join(OpenCodeConfigDir(), "plugin", "vibe-rpc.js")
}

var openCodeVersionRe = regexp.MustCompile(`(\d+)\.\d+`)

// parseOpenCodeMajor pulls the major version out of `opencode --version`
// output ("1.18.20", "opencode v2.4.1"); 0 means unknown.
func parseOpenCodeMajor(out string) int {
	m := openCodeVersionRe.FindStringSubmatch(out)
	if m == nil {
		return 0
	}
	n, _ := strconv.Atoi(m[1])
	return n
}

// openCodeMajor is the installed OpenCode's major version, or 0 if it can't
// be determined. A variable so tests can pin it.
var openCodeMajor = func() int {
	bin := detect.OpenCodeBinary()
	if bin == "" {
		return 0
	}
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	out, err := exec.CommandContext(ctx, bin, "--version").Output()
	if err != nil {
		return 0
	}
	return parseOpenCodeMajor(string(out))
}

// OpenCodePlugin renders the plugin source for binPath, for the installed
// OpenCode. Unknown versions get the current (2.x) API.
func OpenCodePlugin(binPath string) string {
	return renderOpenCodePlugin(binPath, openCodeMajor())
}

func renderOpenCodePlugin(binPath string, major int) string {
	src := openCodePluginSourceV2
	if major == 1 {
		src = openCodePluginSourceV1
	}
	return strings.ReplaceAll(src, "__VIBE_RPC_BIN__", strconv.Quote(binPath))
}

// InstallOpenCodePlugin writes (or refreshes) the plugin. It never overwrites
// a file at that path that vibe-rpc didn't write.
func InstallOpenCodePlugin(binPath string) (bool, error) {
	if binPath == "" {
		binPath = ResolveBinary()
	}
	p := OpenCodePluginPath()
	want := []byte(OpenCodePlugin(binPath))
	if cur, err := os.ReadFile(p); err == nil {
		if !bytes.Contains(cur, []byte(openCodePluginMarker)) {
			return false, errors.New(p + " exists and wasn't written by vibe-rpc; leaving it alone")
		}
		if bytes.Equal(cur, want) {
			return false, nil
		}
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return false, err
	}
	return true, paths.WriteFileAtomic(p, want, 0o644)
}

// UninstallOpenCodePlugin removes the plugin if it's vibe-rpc's.
func UninstallOpenCodePlugin() (bool, error) {
	p := OpenCodePluginPath()
	cur, err := os.ReadFile(p)
	if errors.Is(err, os.ErrNotExist) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	if !bytes.Contains(cur, []byte(openCodePluginMarker)) {
		return false, nil
	}
	return true, os.Remove(p)
}

// OpenCodePluginInstalled reports whether vibe-rpc's plugin is present.
func OpenCodePluginInstalled() bool {
	b, err := os.ReadFile(OpenCodePluginPath())
	return err == nil && bytes.Contains(b, []byte(openCodePluginMarker))
}

const openCodePluginSourceV1 = `// ` + openCodePluginMarker + `
// Generated by vibe-rpc (https://github.com/chauveaul/vibe-rpc). Forwards
// OpenCode events to vibe-rpc for Discord Rich Presence, analytics and
// VibeNotch. Remove with: vibe-rpc uninstall (or delete this file).
import { spawn } from "node:child_process"

const BIN = __VIBE_RPC_BIN__

export const VibeRpc = async ({ directory }) => {
  const dirs = new Map()   // sessionID -> project directory
  const models = new Map() // sessionID -> model id

  // Fire and forget: OpenCode never waits on vibe-rpc, and a missing or
  // failing binary can't break OpenCode.
  const send = (event, payload) => {
    try {
      const child = spawn(BIN, ["hook", event, "--source", "opencode"], { stdio: ["pipe", "ignore", "ignore"] })
      child.on("error", () => {})
      child.stdin.on("error", () => {})
      child.stdin.end(JSON.stringify(payload))
    } catch {}
  }
  const base = (sid) => ({ session_id: sid, cwd: dirs.get(sid) || directory, model: models.get(sid) })

  return {
    event: async ({ event }) => {
      const p = event.properties || {}
      switch (event.type) {
        case "session.created": {
          const info = p.info || {}
          if (info.directory) dirs.set(info.id, info.directory)
          send("SessionStart", { ...base(info.id), source: "startup" })
          break
        }
        case "session.updated": {
          const info = p.info || {}
          if (info.directory) dirs.set(info.id, info.directory)
          break
        }
        case "message.updated": {
          const info = p.info || {}
          if (info.role === "assistant" && info.modelID) models.set(info.sessionID, info.modelID)
          break
        }
        case "session.idle":
          send("Stop", base(p.sessionID))
          break
        case "session.compacted":
          send("PostCompact", base(p.sessionID))
          break
        case "session.deleted":
          if (p.info && p.info.id) send("SessionEnd", base(p.info.id))
          break
        case "permission.updated":
          send("Notification", {
            ...base(p.sessionID),
            message: p.title ? "OpenCode needs permission: " + p.title : "OpenCode needs your permission",
            notification_type: "permission_prompt",
          })
          break
        case "permission.replied":
          send("PermissionReplied", base(p.sessionID))
          break
      }
    },
    "chat.message": async (input) => {
      if (input.model && input.model.modelID) models.set(input.sessionID, input.model.modelID)
      send("UserPromptSubmit", base(input.sessionID))
    },
    "tool.execute.before": async (input, output) => {
      send("PreToolUse", { ...base(input.sessionID), tool_name: input.tool, tool_input: output.args || {} })
    },
    "tool.execute.after": async (input) => {
      send("PostToolUse", { ...base(input.sessionID), tool_name: input.tool, tool_input: input.args || {} })
    },
  }
}
`

// openCodePluginSourceV2 targets OpenCode 2.x: setup(context) subscribes to
// context.event and registers context.session / context.tool hooks.
const openCodePluginSourceV2 = `// ` + openCodePluginMarker + `
// Generated by vibe-rpc (https://github.com/chauveaul/vibe-rpc). Forwards
// OpenCode events to vibe-rpc for Discord Rich Presence, analytics and
// VibeNotch. Remove with: vibe-rpc uninstall (or delete this file).
import { spawn } from "node:child_process"
import { join } from "node:path"

const BIN = __VIBE_RPC_BIN__

// Fire and forget: OpenCode never waits on vibe-rpc, and a missing or
// failing binary can't break OpenCode. Calls run one at a time, in order:
// a hook (prompt) can fire before the matching event (session.created)
// arrives, and parallel processes would let a later SessionStart reset
// state an earlier UserPromptSubmit already wrote.
let queue = Promise.resolve()
const send = (event, payload) => {
  const body = JSON.stringify(payload)
  queue = queue.then(() => new Promise((done) => {
    const timer = setTimeout(done, 5000)
    const finish = () => { clearTimeout(timer); done() }
    try {
      const child = spawn(BIN, ["hook", event, "--source", "opencode"], { stdio: ["pipe", "ignore", "ignore"] })
      child.on("error", finish)
      child.on("exit", finish)
      child.stdin.on("error", () => {})
      child.stdin.end(body)
    } catch { finish() }
  }))
}

// Per-session project directory and model.
const tracker = (fallbackDir) => {
  const dirs = new Map()
  const models = new Map()
  return {
    dirs,
    models,
    base: (sid) => ({ session_id: sid, cwd: dirs.get(sid) || fallbackDir, model: models.get(sid) }),
    forget: (sid) => { dirs.delete(sid); models.delete(sid) },
  }
}

const EVENTS = [
  "session.created",
  "session.moved",
  "session.model.selected",
  "session.execution.succeeded",
  "session.execution.failed",
  "session.execution.interrupted",
  "session.compaction.ended",
  "session.deleted",
  "permission.asked",
  "permission.replied",
]

const setup = async (ctx) => {
  const { dirs, models, base, forget } = tracker((ctx.location && ctx.location.directory) || process.cwd())
  const where = (loc, subpath) => (loc && loc.directory ? (subpath ? join(loc.directory, subpath) : loc.directory) : undefined)
  const regs = []
  const hook = async (domain, name, fn) => {
    try {
      regs.push(await domain.hook(name, (input) => { try { fn(input || {}) } catch {} }))
    } catch {}
  }

  // Plugins load in the background, so a session can exist before setup runs
  // (opencode run, a resumed session): its session.created is never seen.
  // Announce such sessions on first activity instead.
  const seen = new Set()
  const start = (sid, source) => {
    if (!sid || seen.has(sid)) return
    seen.add(sid)
    send("SessionStart", { ...base(sid), source })
  }

  await hook(ctx.session, "prompt", (p) => {
    start(p.sessionID, "startup")
    send("UserPromptSubmit", base(p.sessionID))
  })
  await hook(ctx.session, "context", (c) => { if (c.model && c.model.id) models.set(c.sessionID, c.model.id) })
  await hook(ctx.tool, "execute.before", (t) => {
    start(t.sessionID, "startup")
    send("PreToolUse", { ...base(t.sessionID), tool_name: t.tool, tool_input: t.input || {} })
  })
  await hook(ctx.tool, "execute.after", (t) => {
    const payload = { ...base(t.sessionID), tool_name: t.tool, tool_input: t.input || {} }
    if (t.status === "error") {
      send("PostToolUseFailure", { ...payload, error: (t.error && t.error.message) || "tool failed" })
    } else {
      send("PostToolUse", payload)
    }
  })

  const handle = (ev) => {
    const d = ev.data || ev.properties || {}
    const sid = d.sessionID
    switch (ev.type) {
      case "session.created": {
        const dir = where(d.location, d.subpath)
        if (dir) dirs.set(sid, dir)
        if (d.model && d.model.id) models.set(sid, d.model.id)
        start(sid, "startup")
        break
      }
      case "session.moved": {
        const dir = where(d.location, d.subpath)
        if (dir) dirs.set(sid, dir)
        break
      }
      case "session.model.selected":
        if (d.model && d.model.id) models.set(sid, d.model.id)
        break
      case "session.execution.interrupted":
        // A superseded run is immediately replaced by the next one.
        if (d.reason !== "superseded") send("Stop", base(sid))
        break
      case "session.execution.succeeded":
      case "session.execution.failed":
        send("Stop", base(sid))
        break
      case "session.compaction.ended":
        send("PostCompact", base(sid))
        break
      case "session.deleted":
        send("SessionEnd", base(sid))
        forget(sid)
        seen.delete(sid)
        break
      case "permission.asked": {
        const what = d.message || [d.action, ...(d.resources || [])].filter(Boolean).join(" ")
        send("Notification", {
          ...base(sid),
          message: what ? "OpenCode needs permission: " + what : "OpenCode needs your permission",
          notification_type: "permission_prompt",
        })
        break
      }
      case "permission.replied":
        send("PermissionReplied", base(sid))
        break
    }
  }

  // Never block plugin startup on the event stream.
  const stop = new AbortController()
  ;(async () => {
    try {
      for await (const ev of ctx.event.subscribe({ types: EVENTS, signal: stop.signal })) {
        try { handle(ev) } catch {}
      }
    } catch {}
  })()

  return async () => {
    stop.abort()
    await Promise.all(regs.map((r) => Promise.resolve(r && r.dispose && r.dispose()).catch(() => {})))
  }
}

export default { id: "vibe-rpc", setup }
`
