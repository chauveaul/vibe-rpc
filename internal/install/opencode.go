package install

import (
	"bytes"
	"errors"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/chauveaul/vibe-rpc/internal/paths"
)

// OpenCode has no shell-hook config like Claude Code; it loads JS plugins from
// ~/.config/opencode/plugin/. vibe-rpc installs a tiny plugin that forwards
// OpenCode's events to `vibe-rpc hook <event> --source opencode` in the same
// JSON shape the Claude Code hooks use, so presence, analytics and the notch's
// permission alerts all work unchanged.

const openCodePluginMarker = "vibe-rpc:opencode-plugin"

// OpenCodeConfigDir is OpenCode's global config dir ($OPENCODE_CONFIG_DIR,
// then $XDG_CONFIG_HOME/opencode, then ~/.config/opencode).
func OpenCodeConfigDir() string {
	if d := os.Getenv("OPENCODE_CONFIG_DIR"); d != "" {
		return d
	}
	if x := os.Getenv("XDG_CONFIG_HOME"); x != "" {
		return filepath.Join(x, "opencode")
	}
	return filepath.Join(paths.HomeDir(), ".config", "opencode")
}

// OpenCodePluginPath is where vibe-rpc's plugin lives.
func OpenCodePluginPath() string {
	return filepath.Join(OpenCodeConfigDir(), "plugin", "vibe-rpc.js")
}

// OpenCodePlugin renders the plugin source for binPath.
func OpenCodePlugin(binPath string) string {
	return strings.ReplaceAll(openCodePluginSource, "__VIBE_RPC_BIN__", strconv.Quote(binPath))
}

// InstallOpenCodePlugin writes (or refreshes) the plugin. It never overwrites
// a file at that path that vibe-rpc didn't write.
func InstallOpenCodePlugin(binPath string) (bool, error) {
	if binPath == "" {
		binPath = ResolveBinary()
	}
	p := OpenCodePluginPath()
	want := []byte(OpenCodePlugin(binPath))
	if cur, err := os.ReadFile(p); err == nil {
		if !bytes.Contains(cur, []byte(openCodePluginMarker)) {
			return false, errors.New(p + " exists and wasn't written by vibe-rpc; leaving it alone")
		}
		if bytes.Equal(cur, want) {
			return false, nil
		}
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return false, err
	}
	return true, paths.WriteFileAtomic(p, want, 0o644)
}

// UninstallOpenCodePlugin removes the plugin if it's vibe-rpc's.
func UninstallOpenCodePlugin() (bool, error) {
	p := OpenCodePluginPath()
	cur, err := os.ReadFile(p)
	if errors.Is(err, os.ErrNotExist) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	if !bytes.Contains(cur, []byte(openCodePluginMarker)) {
		return false, nil
	}
	return true, os.Remove(p)
}

// OpenCodePluginInstalled reports whether vibe-rpc's plugin is present.
func OpenCodePluginInstalled() bool {
	b, err := os.ReadFile(OpenCodePluginPath())
	return err == nil && bytes.Contains(b, []byte(openCodePluginMarker))
}

const openCodePluginSource = `// ` + openCodePluginMarker + `
// Generated by vibe-rpc (https://github.com/chauveaul/vibe-rpc). Forwards
// OpenCode events to vibe-rpc for Discord Rich Presence, analytics and
// VibeNotch. Remove with: vibe-rpc uninstall (or delete this file).
import { spawn } from "node:child_process"

const BIN = __VIBE_RPC_BIN__

export const VibeRpc = async ({ directory }) => {
  const dirs = new Map()   // sessionID -> project directory
  const models = new Map() // sessionID -> model id

  // Fire and forget: OpenCode never waits on vibe-rpc, and a missing or
  // failing binary can't break OpenCode.
  const send = (event, payload) => {
    try {
      const child = spawn(BIN, ["hook", event, "--source", "opencode"], { stdio: ["pipe", "ignore", "ignore"] })
      child.on("error", () => {})
      child.stdin.on("error", () => {})
      child.stdin.end(JSON.stringify(payload))
    } catch {}
  }
  const base = (sid) => ({ session_id: sid, cwd: dirs.get(sid) || directory, model: models.get(sid) })

  return {
    event: async ({ event }) => {
      const p = event.properties || {}
      switch (event.type) {
        case "session.created": {
          const info = p.info || {}
          if (info.directory) dirs.set(info.id, info.directory)
          send("SessionStart", { ...base(info.id), source: "startup" })
          break
        }
        case "session.updated": {
          const info = p.info || {}
          if (info.directory) dirs.set(info.id, info.directory)
          break
        }
        case "message.updated": {
          const info = p.info || {}
          if (info.role === "assistant" && info.modelID) models.set(info.sessionID, info.modelID)
          break
        }
        case "session.idle":
          send("Stop", base(p.sessionID))
          break
        case "session.compacted":
          send("PostCompact", base(p.sessionID))
          break
        case "session.deleted":
          if (p.info && p.info.id) send("SessionEnd", base(p.info.id))
          break
        case "permission.updated":
          send("Notification", {
            ...base(p.sessionID),
            message: p.title ? "OpenCode needs permission: " + p.title : "OpenCode needs your permission",
            notification_type: "permission_prompt",
          })
          break
        case "permission.replied":
          send("PermissionReplied", base(p.sessionID))
          break
      }
    },
    "chat.message": async (input) => {
      if (input.model && input.model.modelID) models.set(input.sessionID, input.model.modelID)
      send("UserPromptSubmit", base(input.sessionID))
    },
    "tool.execute.before": async (input, output) => {
      send("PreToolUse", { ...base(input.sessionID), tool_name: input.tool, tool_input: output.args || {} })
    },
    "tool.execute.after": async (input) => {
      send("PostToolUse", { ...base(input.sessionID), tool_name: input.tool, tool_input: input.args || {} })
    },
  }
}
`
