#!/bin/sh
# Render the Homebrew formula for a vibe-rpc release from GoReleaser's dist/.
#
#   scripts/homebrew-formula.sh <version> [dist-dir] > Formula/vibe-rpc.rb
#
# A formula (not a cask) is used on purpose: Homebrew doesn't quarantine
# formula installs, so the unsigned binary runs without a Gatekeeper prompt,
# and formulas also work with Homebrew on Linux.
set -eu

version="${1:?usage: $0 <version> [dist-dir]}"
version="${version#v}"
dist="${2:-dist}"
sums="$dist/vibe-rpc_${version}_checksums.txt"
base="https://github.com/chauveaul/vibe-rpc/releases/download/v${version}"

[ -f "$sums" ] || { echo "missing $sums" >&2; exit 1; }

sha() {
  s=$(awk -v f="vibe-rpc_${version}_$1.tar.gz" '$2 == f { print $1 }' "$sums")
  [ -n "$s" ] || { echo "no checksum for $1 in $sums" >&2; exit 1; }
  echo "$s"
}

mac=$(sha darwin_all)
lin_amd=$(sha linux_amd64)
lin_arm=$(sha linux_arm64)

cat <<EOF
# typed: false
# frozen_string_literal: true

# Generated by scripts/homebrew-formula.sh for vibe-rpc v${version}. Do not edit.
class VibeRpc < Formula
  desc "Discord Rich Presence and coding analytics for Antigravity and Claude Code"
  homepage "https://github.com/chauveaul/vibe-rpc"
  version "${version}"
  license "MIT"

  # One universal binary serves both Mac architectures.
  on_macos do
    on_intel do
      url "${base}/vibe-rpc_${version}_darwin_all.tar.gz"
      sha256 "${mac}"
    end
    on_arm do
      url "${base}/vibe-rpc_${version}_darwin_all.tar.gz"
      sha256 "${mac}"
    end
  end

  on_linux do
    on_intel do
      url "${base}/vibe-rpc_${version}_linux_amd64.tar.gz"
      sha256 "${lin_amd}"
    end
    on_arm do
      url "${base}/vibe-rpc_${version}_linux_arm64.tar.gz"
      sha256 "${lin_arm}"
    end
  end

  def install
    bin.install "vibe-rpc"
  end

  def caveats
    <<~EOS
      Run this once to wire Antigravity & Claude Code hooks and start the daemon:
        vibe-rpc setup
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/vibe-rpc --version")
  end
end
EOF
