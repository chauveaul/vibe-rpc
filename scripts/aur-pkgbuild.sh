#!/bin/sh
# Render the AUR package (vibe-rpc-bin) for a vibe-rpc release from
# GoReleaser's dist/. Writes PKGBUILD and .SRCINFO into out-dir.
#
#   scripts/aur-pkgbuild.sh <version> [dist-dir] [out-dir]
#
# The package installs the prebuilt Linux release binary, so it needs no Go
# toolchain on the user's machine.
set -eu

version="${1:?usage: $0 <version> [dist-dir] [out-dir]}"
version="${version#v}"
dist="${2:-dist}"
out="${3:-.}"
sums="$dist/vibe-rpc_${version}_checksums.txt"
url="https://github.com/chauveaul/vibe-rpc"
desc="Discord Rich Presence and local coding stats for AI coding agents"

[ -f "$sums" ] || { echo "missing $sums" >&2; exit 1; }

sha() {
  s=$(awk -v f="vibe-rpc_${version}_$1.tar.gz" '$2 == f { print $1 }' "$sums")
  [ -n "$s" ] || { echo "no checksum for $1 in $sums" >&2; exit 1; }
  echo "$s"
}

amd=$(sha linux_amd64)
arm=$(sha linux_arm64)
src_amd="vibe-rpc-${version}-x86_64.tar.gz::${url}/releases/download/v${version}/vibe-rpc_${version}_linux_amd64.tar.gz"
src_arm="vibe-rpc-${version}-aarch64.tar.gz::${url}/releases/download/v${version}/vibe-rpc_${version}_linux_arm64.tar.gz"

mkdir -p "$out"

cat > "$out/PKGBUILD" <<EOF
# Maintainer: chauveaul <https://github.com/chauveaul>
# Generated by scripts/aur-pkgbuild.sh in ${url}. Do not edit here.
pkgname=vibe-rpc-bin
pkgver=${version}
pkgrel=1
pkgdesc="${desc}"
arch=('x86_64' 'aarch64')
url="${url}"
license=('MIT')
provides=('vibe-rpc')
conflicts=('vibe-rpc')
options=('!strip' '!debug')
source_x86_64=("${src_amd}")
source_aarch64=("${src_arm}")
sha256sums_x86_64=('${amd}')
sha256sums_aarch64=('${arm}')

package() {
  install -Dm755 vibe-rpc "\$pkgdir/usr/bin/vibe-rpc"
  install -Dm644 LICENSE "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE"
  install -Dm644 README.md "\$pkgdir/usr/share/doc/\$pkgname/README.md"

  install -d "\$pkgdir/usr/share/bash-completion/completions" \\
    "\$pkgdir/usr/share/zsh/site-functions" \\
    "\$pkgdir/usr/share/fish/vendor_completions.d"
  ./vibe-rpc completion bash > "\$pkgdir/usr/share/bash-completion/completions/vibe-rpc"
  ./vibe-rpc completion zsh > "\$pkgdir/usr/share/zsh/site-functions/_vibe-rpc"
  ./vibe-rpc completion fish > "\$pkgdir/usr/share/fish/vendor_completions.d/vibe-rpc.fish"
}
EOF

# Same content makepkg --printsrcinfo produces; the AUR rejects pushes
# whose .SRCINFO is missing or stale.
cat > "$out/.SRCINFO" <<EOF
pkgbase = vibe-rpc-bin
	pkgdesc = ${desc}
	pkgver = ${version}
	pkgrel = 1
	url = ${url}
	arch = x86_64
	arch = aarch64
	license = MIT
	provides = vibe-rpc
	conflicts = vibe-rpc
	options = !strip
	options = !debug
	source_x86_64 = ${src_amd}
	sha256sums_x86_64 = ${amd}
	source_aarch64 = ${src_arm}
	sha256sums_aarch64 = ${arm}

pkgname = vibe-rpc-bin
EOF
